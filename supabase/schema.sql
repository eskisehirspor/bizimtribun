-- Bizim Tribün database schema for Supabase (PostgreSQL).
-- Safe to run more than once: every statement checks before it creates.
-- Timestamps are ISO-8601 text, the same values the app writes.

CREATE TABLE IF NOT EXISTS teams (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  league TEXT NOT NULL,
  is_forum_active INTEGER NOT NULL DEFAULT 0,
  is_active INTEGER NOT NULL DEFAULT 1,
  city TEXT,
  color_primary TEXT,
  color_secondary TEXT,
  admin_edited_at TEXT
);

CREATE TABLE IF NOT EXISTS leagues (
  id TEXT PRIMARY KEY CHECK (id IN ('super', 'lig1', 'lig2', 'lig3', 'bal')),
  name TEXT NOT NULL,
  sort_order INTEGER NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS seasons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL UNIQUE,
  starts_on TEXT NOT NULL,
  ends_on TEXT NOT NULL,
  is_current INTEGER NOT NULL DEFAULT 0 CHECK (is_current IN (0, 1)),
  created_at TEXT NOT NULL,
  CHECK (ends_on > starts_on)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_seasons_one_current ON seasons(is_current) WHERE is_current = 1;

CREATE TABLE IF NOT EXISTS team_seasons (
  season_id INTEGER NOT NULL REFERENCES seasons(id),
  team_id TEXT NOT NULL REFERENCES teams(id),
  league_id TEXT NOT NULL REFERENCES leagues(id),
  PRIMARY KEY (season_id, team_id)
);

