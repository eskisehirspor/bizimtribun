import fs from "node:fs";
import path from "node:path";
import { seedSql } from "../src/lib/db-seed";

// Writes supabase/setup.sql: the schema plus the starting rows, in one file
// that can be pasted into Supabase's SQL Editor or applied as a migration.
const root = path.join(__dirname, "..");
const schema = fs.readFileSync(path.join(root, "supabase", "schema.sql"), "utf8");
const out = `${schema.trimEnd()}\n\n-- Starting rows (generated by \`npm run db:sql\`).\n\n${seedSql()}`;
fs.writeFileSync(path.join(root, "supabase", "setup.sql"), out);
console.log("wrote supabase/setup.sql");
