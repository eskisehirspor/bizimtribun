import { after } from "node:test";
import type { PGlite } from "@electric-sql/pglite";
import { getDb, setDriverFactoryForTests, wrapDriver, type Db } from "./db";
import { openPglite, pgliteDriver } from "./db-local";
import { seedSql } from "./db-seed";

let pg: Promise<PGlite> | undefined;

// The in-process database would otherwise keep the test process alive.
after(async () => {
  if (pg) await (await pg).close();
});


/**
 * Test-only: one in-process database per test process, emptied and seeded
 * again on every call, so each test starts from a clean site.
 */
export async function freshTestDb() {
  process.env.BIZIM_TRIBUN_TEST = "1";
  pg ??= openPglite();
  const db = await pg;
  setDriverFactoryForTests(async () => pgliteDriver(db));
  await db.exec(`SET search_path TO public`);
  const { rows } = await db.query<{ tablename: string }>(
    `SELECT tablename FROM pg_tables WHERE schemaname = 'public'`,
  );
  await db.exec(
    `TRUNCATE ${rows.map((r) => `"${r.tablename}"`).join(", ")} RESTART IDENTITY CASCADE`,
  );
  await db.exec(seedSql());
  return getDb();
}

let scratchCount = 0;

/** Test DDL is written SQLite-style; PostgreSQL wants identity columns. */
function scratchDdl(sql: string) {
  return sql
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/gi, "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace(/INTEGER PRIMARY KEY(?!\s+(REFERENCES|GENERATED))/gi, "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
}

/**
 * Test-only: an empty database (its own schema) for tests that build just the
 * few tables they need.
 */
export async function scratchDb(): Promise<Db> {
  process.env.BIZIM_TRIBUN_TEST = "1";
  pg ??= openPglite();
  const db = await pg;
  const schema = `scratch_${process.pid}_${++scratchCount}`;
  await db.exec(`CREATE SCHEMA ${schema}; SET search_path TO ${schema};`);
  const inner = wrapDriver(pgliteDriver(db));
  return {
    ...inner,
    exec: (sql: string) => inner.exec(scratchDdl(sql)),
  };
}

/** Test-only: runs the seed again over the current data, as a new deploy would. */
export async function reseedTestDb() {
  const db = await (pg ??= openPglite());
  await db.exec(seedSql());
}
